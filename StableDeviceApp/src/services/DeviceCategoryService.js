/**
 * 根据爬虫返回的category字符串，匹配本地类目数据结构
 * @param {string} categoryName 爬虫返回的类目名（如 "贴片电阻"）
 * @returns {{ big: string, small: string } | null}
 */
export function matchCategory(categoryName) {
  if (!categoryName || typeof categoryName !== 'string') return null;
  const target = categoryName.trim();
  for (const cat of DEVICE_CATEGORIES) {
    if (cat.subCategories.includes(target)) {
      return { big: cat.name, small: target };
    }
    // 大类名也匹配（如直接返回"电阻"）
    if (cat.name === target) {
      return { big: cat.name, small: cat.name };
    }
  }
  return null;
}

/**
 * 检查某个 category 值是否在当前分类树中（精确匹配某个子类目）
 * @param {string} categoryValue
 * @returns {Promise<boolean>}
 */
export async function isCategoryInTree(categoryValue) {
  if (!categoryValue || typeof categoryValue !== 'string') return false;
  const categories = await getCategories();
  if (!Array.isArray(categories)) return false;
  const target = categoryValue.trim();
  for (const cat of categories) {
    if ((cat.subCategories || []).includes(target)) return true;
  }
  return false;
}

/**
 * 根据器件的现有信息，自动归类到合适的子类目
 * 用于：扫码上架时 QR 没带类目、Excel 导入时缺类目列等场景
 *
 * 匹配策略（按优先级）：
 *   1. 器件已有 category 字段且精确匹配某个子类目 → 直接用
 *   2. 器件已有 category 匹配某个大类名 → 用该大类的第一个子类目
 *   3. 在器件的 name/package/notes/value/brand 中搜索子类目关键词 → 用命中的子类目
 *      （多个匹配时取最长的，避免"电阻"覆盖"贴片电阻"）
 *   4. 都不匹配 → 返回 null
 *
 * @param {Object} device - 器件对象
 * @returns {Promise<{big: string, sub: string, source: string} | null>}
 */
export async function autoClassifyDevice(device) {
  if (!device || typeof device !== 'object') return null;
  try {
    const categories = await getCategories();
    if (!Array.isArray(categories) || categories.length === 0) return null;

    // 把分类树展平成 [{big, sub}, ...] 方便后续匹配
    const flatList = [];
    for (const big of categories) {
      const subs = Array.isArray(big.subCategories) ? big.subCategories : [];
      for (const sub of subs) {
        flatList.push({ big: big.name, sub, len: sub.length });
      }
    }

    // 1) 精确匹配子类目
    if (device.category) {
      const cat = String(device.category).trim();
      const hit = flatList.find((f) => f.sub === cat);
      if (hit) return { big: hit.big, sub: hit.sub, source: 'exact-sub' };
      // 2) 匹配大类名 → 取该大类的第一个子类目
      const bigHit = categories.find((b) => b.name === cat);
      if (bigHit && Array.isArray(bigHit.subCategories) && bigHit.subCategories.length > 0) {
        return { big: bigHit.name, sub: bigHit.subCategories[0], source: 'exact-big' };
      }
    }

    // 3) 在 name / package / notes / value / brand 中搜索关键词
    const searchText = [
      device.name,
      device.package,
      device.notes,
      device.value,
      device.brand,
    ]
      .filter((v) => typeof v === 'string' && v.trim().length > 0)
      .join(' ')
      .toLowerCase();
    if (searchText.trim()) {
      const candidates = flatList.filter((f) => searchText.includes(f.sub.toLowerCase()));
      if (candidates.length > 0) {
        // 多个命中：选最长的（更具体），并列时长的大类名优先
        candidates.sort((a, b) => b.len - a.len);
        return { big: candidates[0].big, sub: candidates[0].sub, source: 'name-match' };
      }
    }

    return null;
  } catch (err) {
    console.warn('[autoClassifyDevice] 失败:', err);
    return null;
  }
}

/**
 * 默认大分类名集合（用于判断某个大分类是否为内置默认项）
 */
export const DEFAULT_BIG_CATEGORY_NAMES = new Set(
  DEVICE_CATEGORIES.map((c) => c.name)
);

/**
 * 默认子类目映射：bigName -> Set<defaultSubNames>
 */
export const DEFAULT_SUB_CATEGORY_MAP = (() => {
  const map = {};
  for (const cat of DEVICE_CATEGORIES) {
    map[cat.name] = new Set(cat.subCategories);
  }
  return map;
})();

/**
 * 判断某个大分类是否为内置默认项
 * @param {string} bigName
 * @returns {boolean}
 */
export function isDefaultBigCategory(bigName) {
  return DEFAULT_BIG_CATEGORY_NAMES.has(bigName);
}

/**
 * 判断某个子类目是否为内置默认项
 * @param {string} bigName
 * @param {string} subName
 * @returns {boolean}
 */
export function isDefaultSubCategory(bigName, subName) {
  const set = DEFAULT_SUB_CATEGORY_MAP[bigName];
  return set ? set.has(subName) : false;
}

/**
 * 重命名某大分类（仅支持用户新增的大类；默认大类不可重命名）
 * @param {string} oldName - 旧名称
 * @param {string} newName - 新名称
 * @returns {Promise<Array>} 更新后的类目数组
 * @throws {Error} 名称为空、默认大类不可重命名、新名称与已有大类冲突时抛出错误
 */
export async function renameBigCategory(oldName, newName) {
  const trimmed = (newName || '').trim();
  if (!trimmed) {
    throw new Error('大分类名称不能为空');
  }
  if (trimmed === oldName) {
    return getCategories(); // 没变化
  }
  if (isDefaultBigCategory(oldName)) {
    throw new Error(`默认大分类 "${oldName}" 不可重命名`);
  }
  const list = await getCategories();
  const target = list.find((c) => c.name === oldName);
  if (!target) {
    throw new Error(`大分类 "${oldName}" 不存在`);
  }
  if (list.some((c) => c.name === trimmed)) {
    throw new Error(`大分类 "${trimmed}" 已存在`);
  }
  target.name = trimmed;
  await saveCategories(list);
  return list;
}

/**
 * 重命名某大类下的某子类目（仅支持用户新增的子类目；默认子类目不可重命名）
 * @param {string} bigName
 * @param {string} oldSub
 * @param {string} newSub
 * @returns {Promise<Array>} 更新后的类目数组
 * @throws {Error} 名称为空、默认子类目不可重命名、新名称与同大类下其他子类目冲突时抛出错误
 */
export async function renameSubCategory(bigName, oldSub, newSub) {
  const trimmed = (newSub || '').trim();
  if (!trimmed) {
    throw new Error('子类目名称不能为空');
  }
  if (trimmed === oldSub) {
    return getCategories();
  }
  if (isDefaultSubCategory(bigName, oldSub)) {
    throw new Error(`默认子类目 "${oldSub}" 不可重命名`);
  }
  const list = await getCategories();
  const target = list.find((c) => c.name === bigName);
  if (!target) {
    throw new Error(`大分类 "${bigName}" 不存在`);
  }
  if (!target.subCategories.includes(oldSub)) {
    throw new Error(`子类目 "${oldSub}" 在 "${bigName}" 中不存在`);
  }
  if (target.subCategories.includes(trimmed)) {
    throw new Error(`子类目 "${trimmed}" 在 "${bigName}" 中已存在`);
  }
  target.subCategories = target.subCategories.map((s) => (s === oldSub ? trimmed : s));
  await saveCategories(list);
  return list;
}

/**
 * 获取当前生效的类目列表（深拷贝，避免外部修改原数组）
 * 优先从存储中读取用户自定义类目；未设置时返回默认类目
 * @returns {Promise<Array>} 类目数据数组
 */
export async function getCategories() {
  const stored = await StorageService.getCategories();
  const list = stored && Array.isArray(stored) && stored.length > 0
    ? stored
    : DEVICE_CATEGORIES;
  return list.map((cat) => ({
    name: cat.name,
    subCategories: Array.isArray(cat.subCategories) ? [...cat.subCategories] : [],
  }));
}

